// Writes contracts/test/fixtures/zk-batch.json: a 16-order batch and its proof, for the Foundry tests of
// ObscuraAuctionZK. Traders are Foundry's makeAddr("zk-trader-i") addresses, so the test can recreate them.
// Run after every `npm run zk:setup` (a new setup means a new verifier, so old proofs stop verifying).
// Usage: npm run zk:fixture

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Wallet, keccak256, toUtf8Bytes } from "ethers";
import { CONTRACTS_DIR, ZK_SLOTS, type ZkOrder, type ZkSlot, zkCommitment } from "@obscura/shared";
import { proveClearing, shutdownProver, solveZkBatch, verifyClearing } from "@obscura/solver";

const EPOCH = 0n;
const e18 = 10n ** 18n;
const labels = Array.from({ length: ZK_SLOTS }, (_, i) => `zk-trader-${i}`);
const traders = labels.map((l) => new Wallet(keccak256(toUtf8Bytes(l))).address); // = forge-std makeAddr(l)

// Every trader deposits 1,000 TKN and 200,000 mUSD, except slot 14, a buyer who deposits only 1,000 mUSD:
// too little for their order, so it must not trade (and must not block the batch).
const depositBase = traders.map(() => 1_000n * e18);
const depositQuote = traders.map((_, i) => (i === 14 ? 1_000n : 200_000n) * e18);

// 8 buyers and 8 sellers around 100.00 mUSD per TKN (10,000 ticks), 1 to 19 TKN each.
const orders: ZkOrder[] = traders.map((_, i) => ({
  isBuy: i % 2 === 0,
  limitTicks: i % 2 === 0 ? 9_950n + BigInt(i) * 20n : 9_900n + BigInt(i) * 15n,
  amountLots: 1_000n + BigInt(i) * 1_200n,
  salt: BigInt(keccak256(toUtf8Bytes(`zk-salt-${i}`))) >> 8n,
}));

const slots: ZkSlot[] = traders.map((trader, i) => ({
  trader,
  commitment: zkCommitment(trader, EPOCH, orders[i]!),
  lockBase: depositBase[i]!,
  lockQuote: depositQuote[i]!,
}));
// Slot 15's trader never sent their order to the solver: it stays sealed and is left out.
const openings = orders.map((o, i) => (i === 15 ? null : o));

const cleared = solveZkBatch(EPOCH, slots, openings);
const proof = await proveClearing(cleared.input);
if (!(await verifyClearing(proof))) throw new Error("the fixture proof does not verify");
await shutdownProver();

const str = (xs: bigint[]) => xs.map(String);
const fixture = {
  note: "Generated by circuits/clearing/fixture.ts after npm run zk:setup. Do not edit by hand.",
  labels,
  depositBase: str(depositBase),
  depositQuote: str(depositQuote),
  commitments: str(slots.map((s) => s.commitment)),
  isBuy: orders.map((o) => o.isBuy),
  priceTicks: cleared.priceTicks.toString(),
  fillsLots: str(cleared.fillsLots),
  fillEnc: str(cleared.fillEnc),
  included: str(cleared.included),
  a: str(proof.a),
  b: proof.b.map(str),
  c: str(proof.c),
  provingMs: proof.ms,
};
const out = join(CONTRACTS_DIR, "test", "fixtures");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "zk-batch.json"), JSON.stringify(fixture, null, 2) + "\n");
console.log(
  `wrote contracts/test/fixtures/zk-batch.json: price ${cleared.priceTicks} ticks, ` +
    `${cleared.volumeLots} lots matched, proved in ${proof.ms} ms`,
);
