// Spike B: run the whole zero-knowledge pipeline once, end to end.
//
//   1. compile the circuit (circom)
//   2. trusted setup (a small local ceremony, for this spike only)
//   3. prove: "I know an order and salt that hash to this commitment"
//   4. verify the proof off-chain
//   5. export a Solidity verifier and the proof as a Foundry test fixture
//
// Then `forge test` checks the same proof on-chain.
// Usage: npm run spike:zk

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const build = join(root, "circuits", "build", "spikes");
const circuit = join(root, "circuits", "spikes", "sealed_order.circom");
const snarkjsCli = join(root, "node_modules", "snarkjs", "build", "cli.cjs");
const verifierOut = join(root, "contracts", "test", "spikes", "SpikeVerifier.sol");
const fixtureOut = join(root, "contracts", "test", "fixtures", "spike-proof.json");

// Example private inputs. Any values work; the proof never reveals them.
const INPUT = { order: "42", salt: "918273645" };

function circomBinary() {
  const exe = process.platform === "win32" ? "circom.exe" : "circom";
  const local = join(homedir(), ".circom", "bin", exe);
  return existsSync(local) ? local : "circom";
}

function run(label, cmd, args) {
  console.log(`\n> ${label}`);
  execFileSync(cmd, args, { cwd: root, stdio: "inherit" });
}

const snarkjs = (label, ...args) => run(label, process.execPath, [snarkjsCli, ...args]);
const out = (name) => join(build, name);

mkdirSync(build, { recursive: true });

run("compile circuit", circomBinary(), [
  circuit,
  "--r1cs",
  "--wasm",
  "-o",
  build,
  "-l",
  join(root, "node_modules"),
]);

// Local powers-of-tau ceremony. 2^10 constraints is plenty for one Poseidon hash.
// Stage 4 uses a public ceremony file instead; a one-person ceremony is fine for a spike.
snarkjs("powers of tau: start", "powersoftau", "new", "bn128", "10", out("pot_0.ptau"));
snarkjs(
  "powers of tau: contribute",
  "powersoftau",
  "contribute",
  out("pot_0.ptau"),
  out("pot_1.ptau"),
  "--name=spike",
  "-e=obscura spike b entropy",
);
snarkjs(
  "powers of tau: prepare phase 2",
  "powersoftau",
  "prepare",
  "phase2",
  out("pot_1.ptau"),
  out("pot_final.ptau"),
);

snarkjs(
  "circuit key: setup",
  "groth16",
  "setup",
  out("sealed_order.r1cs"),
  out("pot_final.ptau"),
  out("key_0.zkey"),
);
snarkjs(
  "circuit key: contribute",
  "zkey",
  "contribute",
  out("key_0.zkey"),
  out("key_final.zkey"),
  "--name=spike",
  "-e=obscura spike b key entropy",
);
snarkjs(
  "export verification key",
  "zkey",
  "export",
  "verificationkey",
  out("key_final.zkey"),
  out("vk.json"),
);

writeFileSync(out("input.json"), JSON.stringify(INPUT));
snarkjs(
  "prove",
  "groth16",
  "fullprove",
  out("input.json"),
  join(build, "sealed_order_js", "sealed_order.wasm"),
  out("key_final.zkey"),
  out("proof.json"),
  out("public.json"),
);
snarkjs("verify off-chain", "groth16", "verify", out("vk.json"), out("public.json"), out("proof.json"));

// Solidity verifier, renamed so it cannot clash with the real verifier in Stage 4.
snarkjs(
  "export Solidity verifier",
  "zkey",
  "export",
  "solidityverifier",
  out("key_final.zkey"),
  out("verifier.sol"),
);
mkdirSync(dirname(verifierOut), { recursive: true });
writeFileSync(
  verifierOut,
  readFileSync(out("verifier.sol"), "utf8").replace(/contract Groth16Verifier/, "contract SpikeVerifier"),
);

// Proof as Solidity calldata: "[a],[[b],[b]],[c],[public]". Parse it into a JSON fixture.
console.log("\n> export proof calldata");
const calldata = execFileSync(
  process.execPath,
  [snarkjsCli, "zkey", "export", "soliditycalldata", out("public.json"), out("proof.json")],
  { cwd: root, encoding: "utf8" },
);
const [a, b, c, pub] = JSON.parse(`[${calldata.trim()}]`);
const toDecimal = (hex) => BigInt(hex).toString();
const fixture = {
  note: "Generated by circuits/spikes/spike-b.mjs. Do not edit by hand.",
  a: a.map(toDecimal),
  b: b.map((row) => row.map(toDecimal)),
  c: c.map(toDecimal),
  publicSignals: pub.map(toDecimal),
};
mkdirSync(dirname(fixtureOut), { recursive: true });
writeFileSync(fixtureOut, JSON.stringify(fixture, null, 2) + "\n");

console.log(
  `\nSpike B done.\n  commitment (public): ${fixture.publicSignals[0]}\n  verifier: ${verifierOut}\n  fixture:  ${fixtureOut}`,
);
