// Copies contract ABIs from Foundry's build output into typed TypeScript modules.
// Usage: npm run abis   (builds the contracts first)

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const CONTRACTS = ["MockERC20", "SimpleAMM", "ObscuraAuction", "InvariantBounty", "ObscuraAuctionZK"];

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const outDir = join(here, "..", "src", "abis");
mkdirSync(outDir, { recursive: true });

for (const name of CONTRACTS) {
  const artifact = JSON.parse(
    readFileSync(join(root, "contracts", "out", `${name}.sol`, `${name}.json`), "utf8"),
  );
  const source =
    `// Generated by packages/shared/scripts/gen-abis.mjs from contracts/out. Do not edit.\n` +
    `export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(outDir, `${name}.ts`), source);
  console.log(`wrote src/abis/${name}.ts (${artifact.abi.length} entries)`);
}

writeFileSync(
  join(outDir, "index.ts"),
  `// Generated by packages/shared/scripts/gen-abis.mjs. Do not edit.\n` +
    CONTRACTS.map((name) => `export { ${name}Abi } from "./${name}.ts";`).join("\n") +
    "\n",
);
