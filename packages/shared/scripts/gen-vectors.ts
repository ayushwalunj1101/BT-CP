// Writes commitment-hash test vectors that both the TypeScript and Solidity test suites check.
// If either side ever hashes an order differently, one of them fails.
// Usage: npx tsx packages/shared/scripts/gen-vectors.ts

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { getAddress, keccak256, toBeHex, toUtf8Bytes, zeroPadValue } from "ethers";
import { CONTRACTS_DIR } from "../src/paths.ts";
import { type SealedOrder, commitmentHash } from "../src/order.ts";

const MAX_UINT128 = 2n ** 128n - 1n;

/** Deterministic pseudo-random values, so the file is identical every time it is generated. */
const seeded = (label: string, i: number) => BigInt(keccak256(toUtf8Bytes(`${label}-${i}`)));

type Vector = { trader: string; epoch: bigint; order: SealedOrder };
const vectors: Vector[] = [];

// Edge cases first.
vectors.push({
  trader: getAddress("0x0000000000000000000000000000000000000001"),
  epoch: 0n,
  order: { isBuy: true, limitPrice: 1n, amount: 1n, salt: zeroPadValue("0x00", 32) },
});
vectors.push({
  trader: getAddress("0xffffffffffffffffffffffffffffffffffffffff"),
  epoch: 2n ** 64n,
  order: { isBuy: false, limitPrice: MAX_UINT128, amount: MAX_UINT128, salt: "0x" + "ff".repeat(32) },
});
// Then realistic orders.
for (let i = 0; i < 14; i++) {
  vectors.push({
    trader: getAddress("0x" + (seeded("trader", i) % 2n ** 160n).toString(16).padStart(40, "0")),
    epoch: seeded("epoch", i) % 1_000n,
    order: {
      isBuy: i % 2 === 0,
      limitPrice: 90n * 10n ** 18n + (seeded("price", i) % (20n * 10n ** 18n)),
      amount: 1n + (seeded("amount", i) % (5_000n * 10n ** 18n)),
      salt: toBeHex(seeded("salt", i), 32),
    },
  });
}

const file = {
  note: "Generated by packages/shared/scripts/gen-vectors.ts. Do not edit by hand.",
  traders: vectors.map((v) => v.trader),
  epochs: vectors.map((v) => v.epoch.toString()),
  isBuys: vectors.map((v) => v.order.isBuy),
  limitPrices: vectors.map((v) => v.order.limitPrice.toString()),
  amounts: vectors.map((v) => v.order.amount.toString()),
  salts: vectors.map((v) => v.order.salt),
  hashes: vectors.map((v) => commitmentHash(v.trader, v.epoch, v.order)),
};

const outDir = join(CONTRACTS_DIR, "test", "vectors");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "commitments.json"), JSON.stringify(file, null, 2) + "\n");
console.log(`wrote contracts/test/vectors/commitments.json (${vectors.length} vectors)`);
