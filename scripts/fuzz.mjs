// The long invariant campaign (feature F11): runs the fuzzer with the "long" Foundry profile, counts how
// far the random runs got, and writes results/fuzz-report.md for the report.
// Usage: npm run fuzz

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(root, "contracts");
const results = join(root, "results");
const statsFile = join(results, "fuzz-stats.csv");
const reportFile = join(results, "fuzz-report.md");

const exe = process.platform === "win32" ? "forge.exe" : "forge";
const forge = existsSync(join(homedir(), ".foundry", "bin", exe))
  ? join(homedir(), ".foundry", "bin", exe)
  : "forge";

mkdirSync(results, { recursive: true });
rmSync(statsFile, { force: true });

const profile = readFileSync(join(contracts, "foundry.toml"), "utf8").match(
  /\[profile\.long\.invariant\][^[]*?runs\s*=\s*(\d+)[^[]*?depth\s*=\s*(\d+)/,
);
const [runs, depth] = profile ? [Number(profile[1]), Number(profile[2])] : [0, 0];
console.log(`Long invariant campaign: ${runs} runs × ${depth} calls each. This takes a few minutes…\n`);

const started = Date.now();
const run = spawnSync(
  forge,
  ["test", "--match-contract", "ObscuraInvariantsTest", "--match-test", "invariant"],
  {
    cwd: contracts,
    env: { ...process.env, FOUNDRY_PROFILE: "long", FUZZ_STATS: "true", FUZZ_STATS_FILE: statsFile },
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  },
);
const seconds = Math.round((Date.now() - started) / 1000);
const output = `${run.stdout}\n${run.stderr}`;
const passed = run.status === 0 && /Suite result: ok/.test(output);

// One line per run: commit, reveal, submitHonest, submitCorrupt, settle, settledWithTrades, voided, other.
const lines = existsSync(statsFile) ? readFileSync(statsFile, "utf8").trim().split("\n") : [];
const rows = lines
  .map((l) => l.split(",").map(Number))
  .filter((r) => r.length === 8 && r.every(Number.isFinite));
const total = (i) => rows.reduce((s, r) => s + r[i], 0);
const names = [
  "Orders committed",
  "Orders revealed",
  "Honest solutions submitted",
  "Corrupted solutions submitted",
  "settle() calls",
  "Batches settled with trades",
  "Batches voided (no valid solution)",
  "Other actions (deposits, withdrawals, donations, time jumps)",
];
const invariants = [...output.matchAll(/\[(PASS|FAIL)[^\]]*\]\s+(invariant_\w+)/g)].map(
  (m) => `| ${m[2]} | ${m[1]} |`,
);
const forgeVersion = spawnSync(forge, ["--version"], { encoding: "utf8" }).stdout.split("\n")[0];

const report = `# Invariant fuzzing report

Generated by \`npm run fuzz\` on ${new Date().toISOString().slice(0, 10)} with ${forgeVersion}.

**Result: ${passed ? "no invariant was broken" : "AN INVARIANT FAILED, see the output below"}.**

Campaign: ${runs} runs of ${depth} random calls each (${(runs * depth).toLocaleString("en-US")} calls in total), ${seconds} s.
After every single call, every invariant below was checked.

| Invariant | Result |
|---|---|
${invariants.join("\n")}

## How far the random runs got

Counted over ${rows.length.toLocaleString("en-US")} runs.

| Action | Total |
|---|---|
${names.map((n, i) => `| ${n} | ${total(i).toLocaleString("en-US")} |`).join("\n")}
${passed ? "" : `\n## Forge output\n\n\`\`\`\n${output.slice(-6000)}\n\`\`\`\n`}`;

writeFileSync(reportFile, report);
rmSync(statsFile, { force: true });
console.log(report);
console.log(`Report written to ${reportFile}`);
process.exit(passed ? 0 : 1);
